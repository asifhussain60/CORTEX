class TestInlineResponseEnforcement:
    """Verify CORE-002: all responses must be inline, no .md/.txt report files created."""

    def test_no_report_md_files_created_by_orchestrators(self) -> None:
        """No orchestrator source file may write() to .md or .txt report files."""
        orch_root = ROOT / "cortex" / "orchestrators"
        violations = []
        # Pattern: writing to a file ending in .md or .txt via open() or Path.write_*
        report_write_pattern = re.compile(
            r'open\([^)]+\.(md|txt)["\']',
            re.IGNORECASE,
        )
        for py_file in orch_root.rglob("*.py"):
            content = py_file.read_text(errors="replace")
            if report_write_pattern.search(content):
                violations.append(str(py_file.relative_to(ROOT)))
        assert violations == [], (
            f"Orchestrators writing to .md/.txt report files (CORE-002 violation): {violations}"
        )

    def test_cortex_generate_no_report_file_in_tests(self) -> None:
        """Golden tests must not assert on .md or .txt files generated by orchestrators."""
        golden_root = ROOT / "tests" / "golden"
        violations = []
        # Files that assert on a generated report filename
        report_assert_pattern = re.compile(
            r'assert.*\.(md|txt).*report',
            re.IGNORECASE,
        )
        for py_file in golden_root.rglob("*.py"):
            content = py_file.read_text(errors="replace")
            if report_assert_pattern.search(content):
                violations.append(str(py_file.relative_to(ROOT)))
        # This is a soft check — warn only
        if violations:
            pytest.xfail(
                f"Golden tests assert on generated report files (CORE-002 concern): {violations}"
            )


class TestResponseIconMapping:
    """Each intent type must have a canonical icon in response format."""

    def test_response_template_reference_has_intent_icons(self) -> None:
        """cortex-response-templates.md or equivalent must define intent icons."""
        template_candidates = [
            ROOT / ".github" / "templates" / "cortex-response-templates.md",
        ]
        for candidate in template_candidates:
            if candidate.exists():
                content = candidate.read_text(errors="replace")
                # Must define icons for core intent types
                for intent in ("IMPLEMENT", "FIX", "AUDIT", "REFACTOR"):
                    assert intent in content, (
                        f"cortex-response-templates.md missing icon definition for {intent}"
                    )
                return
        pytest.skip("cortex-response-templates.md not found — skipping icon check")

    def test_master_orchestrator_emits_no_md_files(self) -> None:
        """MasterOrchestrator must not create .md or .txt files — CORE-002."""
        master = ROOT / "cortex" / "orchestrators" / "core" / "master_orchestrator.py"
        if not master.exists():
            pytest.skip("master_orchestrator.py not found")
        content = master.read_text(errors="replace")
        # Should not have open(..., 'w') calls targeting .md / .txt
        has_md_write = re.search(r"open\([^)]+\.(md|txt)['\"].*['\"]w", content)
        assert has_md_write is None, (
            "MasterOrchestrator writes to .md/.txt file — CORE-002 violation"
        )


