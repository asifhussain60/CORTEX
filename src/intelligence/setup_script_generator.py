    def _windows_env_setup(self) -> List[str]:
        """Generate Windows environment variable setup."""
        lines = []
        lines.append("# Environment Variables")
        lines.append("Write-Host 'Setting environment variables...' -ForegroundColor Yellow")
        
        for key, value in self.env_vars.items():
            lines.append(f"$env:{key} = '{value}'")
        
        lines.append("")
        return lines
    
    def _windows_tool_recommendations(self) -> List[str]:
        """Generate Windows tool recommendations."""
        lines = []
        lines.append("# Recommended Development Tools")
        lines.append("Write-Host 'Recommended tools:' -ForegroundColor Cyan")
        
        if "python" in self.by_language:
            lines.append("Write-Host '  Python: pylint, black, pytest, mypy' -ForegroundColor Gray")
            lines.append("Write-Host '    Install: pip install pylint black pytest mypy' -ForegroundColor Gray")
        
        if "javascript" in self.by_language:
            lines.append("Write-Host '  Node.js: eslint, prettier, jest' -ForegroundColor Gray")
            lines.append("Write-Host '    Install: npm install -D eslint prettier jest' -ForegroundColor Gray")
        
        if "csharp" in self.by_language:
            lines.append("Write-Host '  .NET: dotnet-format, StyleCop' -ForegroundColor Gray")
        
        lines.append("")
        return lines
    
    # ===== Unix Helpers =====
    
