    def generate_prompt(self, beat: NarrativeBeat) -> DALLEPrompt:
        """
        Create structured DALL-E prompt from narrative beat.
        
        Args:
            beat: Narrative moment to illustrate
            
        Returns:
            Complete DALL-E prompt with metadata
        """
        # Build filename from convention
        filename = f"cortex-awakening-{beat.chapter}-{beat.sequence:02d}.png"
        
        # Construct DALL-E prompt with specific visual details
        prompt_parts = [
            f"Digital illustration: {beat.scene_description}",
            f"\n\nMood: {beat.mood}",
            f"\n\nKey visual elements:",
        ]
        
        for elem in beat.visual_elements:
            prompt_parts.append(f"- {elem}")
        
        prompt_parts.append(f"\n\nStyle: {self.STYLE_GUIDE.strip()}")
        
        prompt_text = "\n".join(prompt_parts)
        
        return DALLEPrompt(
            filename=filename,
            beat=beat,
            prompt_text=prompt_text,
            style_guide=self.STYLE_GUIDE.strip(),
            technical_notes=self.TECHNICAL_NOTES.strip()
        )
    
    def export_prompts(self, prompts: List[DALLEPrompt]) -> Dict[str, int]:
        """
        Save all prompts to output directory.
        
        Args:
            prompts: Generated DALL-E prompts
            
        Returns:
            Statistics (files created, chapters covered, etc.)
        """
        stats = {
            "total_prompts": len(prompts),
            "chapters_covered": len(set(p.beat.chapter for p in prompts)),
            "chapter_openings": sum(1 for p in prompts if p.beat.placement_type == PlacementType.CHAPTER_OPENING),
            "key_moments": sum(1 for p in prompts if p.beat.placement_type == PlacementType.KEY_MOMENT),
            "character_intros": sum(1 for p in prompts if p.beat.placement_type == PlacementType.CHARACTER_INTRO),
            "comedic_scenes": sum(1 for p in prompts if p.beat.placement_type == PlacementType.COMEDIC_SCENE),
            "technical_diagrams": sum(1 for p in prompts if p.beat.placement_type == PlacementType.TECHNICAL_DIAGRAM),
        }
        
        # Save individual prompt files
        for prompt in prompts:
            prompt_file = self.output_dir / f"{prompt.filename.replace('.png', '.txt')}"
            prompt_file.write_text(prompt.to_file_content(), encoding='utf-8')
        
        # Save master catalog with all filenames (for Phase 2 reference)
        catalog_lines = [
            "# CORTEX Story Illustration Catalog",
            "# Generated DALL-E prompts with filenames for story reference",
            "",
            "## Quick Reference",
            f"Total illustrations: {stats['total_prompts']}",
            f"Chapters covered: {stats['chapters_covered']}",
            "",
            "## Filenames by Chapter",
            ""
        ]
        
        current_chapter = None
        for prompt in sorted(prompts, key=lambda p: (p.beat.chapter, p.beat.sequence)):
            if prompt.beat.chapter != current_chapter:
                current_chapter = prompt.beat.chapter
                catalog_lines.append(f"\n### {prompt.beat.chapter.upper()}")
            
            catalog_lines.append(f"- `{prompt.filename}` - {prompt.beat.title} ({prompt.beat.placement_type.value})")
        
        catalog_lines.append("\n## Usage in Story")
        catalog_lines.append("```markdown")
        catalog_lines.append("![{beat.title}](illustrations/images/{filename})")
        catalog_lines.append("```")
        
        catalog_file = self.output_dir / "ILLUSTRATION-CATALOG.md"
        catalog_file.write_text("\n".join(catalog_lines), encoding='utf-8')
        
        print(f"\n✅ Exported {stats['total_prompts']} prompts to {self.output_dir}")
        print(f"   Chapters: {stats['chapters_covered']}")
        print(f"   Chapter Openings: {stats['chapter_openings']}")
        print(f"   Key Moments: {stats['key_moments']}")
        print(f"   Character Intros: {stats['character_intros']}")
        print(f"   Comedic Scenes: {stats['comedic_scenes']}")
        print(f"   Technical Diagrams: {stats['technical_diagrams']}")
        
        return stats
    
