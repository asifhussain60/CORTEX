class PlacementType(Enum):
    """Where the illustration appears in narrative."""
    CHAPTER_OPENING = "chapter_opening"  # Opening scene, sets mood
    KEY_MOMENT = "key_moment"  # Pivotal narrative beat
    CHARACTER_INTRO = "character_intro"  # Character first appearance
    COMEDIC_SCENE = "comedic_scene"  # Visual humor opportunity
    TECHNICAL_DIAGRAM = "technical_diagram"  # Architecture/concept illustration


@dataclass
class NarrativeBeat:
    """A moment in the story worthy of illustration."""
    chapter: str  # "prologue", "ch01", "ch02", etc.
    title: str  # Human-readable title
    narrative_anchor: str  # Text phrase for finding injection point
    scene_description: str  # What happens in this scene
    visual_elements: List[str]  # Key visual components
    mood: str  # Emotional tone (comedic, tense, triumphant, etc.)
    placement_type: PlacementType
    sequence: int  # 1, 2, 3 within chapter


@dataclass
class DALLEPrompt:
    """Structured DALL-E prompt with metadata."""
    filename: str  # cortex-awakening-{chapter}-{sequence}.png
    beat: NarrativeBeat
    prompt_text: str  # Full DALL-E 3 prompt
    style_guide: str  # Consistent artistic style
    technical_notes: str  # Resolution, aspect ratio, etc.
    
    def to_file_content(self) -> str:
        """Format as saveable text file."""
        return f"""CORTEX Story Illustration Prompt
=====================================

FILENAME: {self.filename}
CHAPTER: {self.beat.chapter}
TITLE: {self.beat.title}
PLACEMENT: {self.beat.placement_type.value}
MOOD: {self.beat.mood}

NARRATIVE ANCHOR:
{self.beat.narrative_anchor}

SCENE DESCRIPTION:
{self.beat.scene_description}

VISUAL ELEMENTS:
{chr(10).join(f"  - {elem}" for elem in self.beat.visual_elements)}

---

DALL-E 3 PROMPT:
{self.prompt_text}

---

STYLE GUIDE:
{self.style_guide}

TECHNICAL NOTES:
{self.technical_notes}

---
Generated by CORTEX Story Enhancement Orchestrator
"""


