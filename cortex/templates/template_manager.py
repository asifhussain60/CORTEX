    def get_domain_templates(self, domain: str) -> List[Dict[str, Any]]:
        """Get templates for a specific domain.
        
        Args:
            domain: Domain name.
            
        Returns:
            List of template dictionaries.
        """
        return self._strategy.get_domain_templates(domain)
    
    def get_template_content(self, template_id: str) -> Optional[str]:
        """Get template content by ID.
        
        Args:
            template_id: Template ID.
            
        Returns:
            Template content or None if not found.
        """
        return self._template_content.get(template_id)
    
    def render_template(self, template_id: str, variables: Dict[str, Any]) -> str:
        """Render template with variables.
        
        Args:
            template_id: Template ID.
            variables: Variables to substitute.
            
        Returns:
            Rendered template content.
            
        Raises:
            ValueError: If template not found or required variables missing.
        """
        content = self.get_template_content(template_id)
        if content is None:
            raise ValueError(f"Template not found: {template_id}")
        
        # Find all variables in template
        required_vars = set(re.findall(r'\{(\w+)\}', content))
        provided_vars = set(variables.keys())
        
        # Check for missing variables
        missing_vars = required_vars - provided_vars
        if missing_vars:
            raise ValueError(f"Missing required variables: {missing_vars}")
        
        # Substitute variables
        rendered = content
        for key, value in variables.items():
            rendered = rendered.replace(f'{{{key}}}', str(value))
        
        return rendered
