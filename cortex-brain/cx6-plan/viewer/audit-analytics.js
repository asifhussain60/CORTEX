/**
 * CORTEX 6.0 - Audit Analytics Dashboard
 * Real-time audit trail visualization with metrics and formatted JSON display
 */

class AuditAnalytics {
    constructor() {
        this.logs = [];
        this.showJSON = false;
        this.charts = {};
        this.refreshInterval = 30000; // 30 seconds
    }

    /**
     * Initialize the dashboard
     */
    async initialize() {
        console.log('Initializing Audit Analytics Dashboard...');
        await this.loadAuditLogs();
        this.updateMetrics();
        this.renderCharts();
        this.renderAuditEntries();
        
        // Auto-refresh every 30 seconds
        setInterval(() => this.refresh(), this.refreshInterval);
    }

    /**
     * Load audit logs from aggregated JSON file
     */
    async loadAuditLogs() {
        try {
            // Load from pre-aggregated file (generated by scripts/aggregate_audit_logs.py)
            const response = await fetch('audit-logs-aggregated.json');
            
            if (response.ok) {
                const data = await response.json();
                this.logs = data.entries || [];
                console.log(`✅ Loaded ${this.logs.length} audit entries from aggregated file`);
                console.log(`   Generated at: ${data.generated_at}`);
                console.log(`   Files processed: ${data.files_processed}`);
            } else {
                console.warn('Aggregated audit file not found. Using mock data.');
                this.logs = this.generateMockLogs();
            }
        } catch (error) {
            console.warn('Could not load audit logs:', error.message);
            console.log('Using mock data for demonstration...');
            this.logs = this.generateMockLogs();
        }
        
        // Sort by timestamp descending
        this.logs.sort((a, b) => new Date(b.timestamp) - new Date(a.timestamp));
        
        // Keep only most recent
        this.logs = this.logs.slice(0, 100);
        
        return this.logs;
    }

    /**
     * Parse JSONL format
     */
    parseJSONL(content) {
        return content.trim().split('\n')
            .filter(line => line.trim())
            .map(line => {
                try {
                    return JSON.parse(line);
                } catch {
                    return null;
                }
            })
            .filter(entry => entry !== null);
    }

    /**
     * Generate mock audit logs for demonstration
     */
    generateMockLogs() {
        const components = [
            'SetupVerificationMiddleware',
            'GovernanceCheckpointMiddleware', 
            'TeardownRefactorMiddleware',
            'MasterOrchestrator',
            'PlanningOrchestrator',
            'AuditLogger',
            'StateManager'
        ];
        
        const operations = [
            'initialize',
            'execute',
            'validate',
            'audit_log',
            'state_transition',
            'governance_check'
        ];
        
        const levels = ['info', 'info', 'info', 'warning', 'error'];
        const categories = ['middleware', 'orchestrator', 'governance', 'state_management'];
        
        const mockLogs = [];
        const now = new Date();
        
        for (let i = 0; i < 50; i++) {
            const timestamp = new Date(now - i * 600000); // 10 minutes apart
            const level = levels[Math.floor(Math.random() * levels.length)];
            const component = components[Math.floor(Math.random() * components.length)];
            const operation = operations[Math.floor(Math.random() * operations.length)];
            const category = categories[Math.floor(Math.random() * categories.length)];
            
            mockLogs.push({
                timestamp: timestamp.toISOString(),
                level: level,
                category: category,
                component: component,
                operation: operation,
                message: `${component} ${operation} ${level === 'error' ? 'failed' : 'completed'}`,
                correlation_id: `CORTEX-${Math.random().toString(36).substr(2, 12).toUpperCase()}`,
                duration_ms: level === 'error' ? null : Math.floor(Math.random() * 500) + 10
            });
        }
        
        return mockLogs;
    }

    /**
     * Get recent log file names (legacy - kept for reference)
     */
    getRecentLogFiles() {
        const files = [];
        const now = new Date();
        
        // Try files from last 7 days (more forgiving)
        for (let i = 0; i < 7; i++) {
            const date = new Date(now - i * 86400000);
            const dateStr = date.toISOString().slice(0, 10).replace(/-/g, '');
            
            // Try multiple times per day
            for (let hour = 0; hour < 24; hour += 3) {
                const hourStr = String(hour).padStart(2, '0');
                files.push(`${dateStr}_${hourStr}0000_middleware.jsonl`);
                files.push(`${dateStr}_${hourStr}0000_state_management.jsonl`);
            }
        }
        
        return files;
    }

    /**
     * Update dashboard metrics
     */
    updateMetrics() {
        const metrics = this.calculateMetrics();
        
        // Optional: Update metric elements if they exist
        const totalOps = document.getElementById('totalOperations');
        const successRate = document.getElementById('successRate');
        const activeComps = document.getElementById('activeComponents');
        const avgTime = document.getElementById('avgResponseTime');
        
        if (totalOps) totalOps.textContent = metrics.total;
        if (successRate) successRate.textContent = metrics.successRate + '%';
        if (activeComps) activeComps.textContent = metrics.components;
        if (avgTime) avgTime.textContent = metrics.avgDuration + 'ms';
        
        console.log('📊 Metrics calculated:', metrics);
    }

    /**
     * Calculate metrics from logs
     */
    calculateMetrics() {
        if (this.logs.length === 0) {
            return { total: 0, successRate: 0, components: 0, avgDuration: 0 };
        }

        const total = this.logs.length;
        const successCount = this.logs.filter(log => 
            log.level === 'info' || log.level === 'debug'
        ).length;
        const successRate = Math.round((successCount / total) * 100);
        
        const components = new Set(this.logs.map(log => log.component)).size;
        
        const durations = this.logs
            .filter(log => log.duration_ms !== null && log.duration_ms !== undefined)
            .map(log => log.duration_ms);
        const avgDuration = durations.length > 0
            ? Math.round(durations.reduce((a, b) => a + b, 0) / durations.length)
            : 0;

        return { total, successRate, components, avgDuration };
    }

    /**
     * Render charts
     */
    renderCharts() {
        this.renderActivityTimeline();
        this.renderCategoryDistribution();
    }

    /**
     * Render activity timeline chart (last 24 entries over time)
     */
    renderActivityTimeline() {
        const ctx = document.getElementById('activityTimelineChart');
        if (!ctx) return;

        // Group logs by hour
        const hourly = {};
        const last24 = this.logs.slice(0, 24);
        
        last24.forEach(log => {
            const hour = new Date(log.timestamp).toLocaleTimeString('en-US', { 
                hour: '2-digit', 
                minute: '2-digit' 
            });
            hourly[hour] = (hourly[hour] || 0) + 1;
        });

        const labels = Object.keys(hourly).reverse();
        const data = Object.values(hourly).reverse();

        if (this.charts.timeline) {
            this.charts.timeline.destroy();
        }

        this.charts.timeline = new Chart(ctx, {
            type: 'line',
            data: {
                labels: labels,
                datasets: [{
                    label: 'Operations',
                    data: data,
                    borderColor: '#00d4ff',
                    backgroundColor: 'rgba(0, 212, 255, 0.1)',
                    fill: true,
                    tension: 0.4
                }]
            },
            options: {
                responsive: true,
                maintainAspectRatio: true,
                plugins: {
                    legend: { display: false }
                },
                scales: {
                    y: {
                        beginAtZero: true,
                        ticks: { color: '#fff' },
                        grid: { color: 'rgba(255,255,255,0.1)' }
                    },
                    x: {
                        ticks: { color: '#fff' },
                        grid: { color: 'rgba(255,255,255,0.1)' }
                    }
                }
            }
        });
    }

    /**
     * Render category distribution pie chart
     */
    renderCategoryDistribution() {
        const ctx = document.getElementById('categoryDistributionChart');
        if (!ctx) return;

        // Count by category
        const categories = {};
        this.logs.forEach(log => {
            const cat = log.category || 'unknown';
            categories[cat] = (categories[cat] || 0) + 1;
        });

        const labels = Object.keys(categories);
        const data = Object.values(categories);
        const colors = [
            '#00d4ff', // cyan
            '#7b2cbf', // purple
            '#ff006e', // pink
            '#06ffa5', // green
            '#ffbe0b', // yellow
            '#fb5607', // orange
        ];

        if (this.charts.category) {
            this.charts.category.destroy();
        }

        this.charts.category = new Chart(ctx, {
            type: 'doughnut',
            data: {
                labels: labels,
                datasets: [{
                    data: data,
                    backgroundColor: colors,
                    borderColor: '#1a1a2e',
                    borderWidth: 2
                }]
            },
            options: {
                responsive: true,
                maintainAspectRatio: true,
                plugins: {
                    legend: {
                        position: 'bottom',
                        labels: { color: '#fff' }
                    }
                }
            }
        });
    }

    /**
     * Render audit entries (formatted or JSON)
     */
    renderAuditEntries() {
        const container = document.getElementById('auditEntriesDisplay');
        if (!container) return;

        if (this.logs.length === 0) {
            container.innerHTML = `
                <div style="grid-column: 1/-1; text-align: center; padding: 2rem; color: rgba(255,255,255,0.5);">
                    <i class="bi bi-info-circle" style="font-size: 2rem;"></i>
                    <p style="margin-top: 1rem;">No audit logs found.</p>
                </div>
            `;
            return;
        }

        // Group logs by category and get summaries
        const summaries = this.generateAuditSummaries();
        
        const html = summaries.map(summary => this.renderAuditCard(summary)).join('');
        container.innerHTML = html;
    }

    /**
     * Generate meaningful audit summaries from logs
     */
    generateAuditSummaries() {
        const summaries = [];
        const categories = {};

        // Group logs by category
        this.logs.forEach(log => {
            const cat = log.category || 'unknown';
            if (!categories[cat]) {
                categories[cat] = [];
            }
            categories[cat].push(log);
        });

        // Create summary for each category
        Object.entries(categories).slice(0, 6).forEach(([category, logs]) => {
            const count = logs.length;
            const successCount = logs.filter(l => l.level === 'info' || l.level === 'debug').length;
            const errorCount = logs.filter(l => l.level === 'error').length;
            const lastLog = logs[0];
            const timestamp = new Date(lastLog.timestamp).toLocaleString();

            const icons = {
                'middleware': '⚙️',
                'governance': '🛡️',
                'state_management': '💾',
                'orchestration': '🎯',
                'validation': '✓',
                'infrastructure': '🏗️',
                'audit': '📊',
                'unknown': '📝'
            };

            const icon = icons[category] || icons['unknown'];

            summaries.push({
                category,
                icon,
                count,
                successCount,
                errorCount,
                successRate: Math.round((successCount / count) * 100),
                lastLog: lastLog.operation || 'Operation executed',
                timestamp,
                level: errorCount > 0 ? 'error' : successCount === count ? 'success' : 'warning'
            });
        });

        return summaries;
    }

    /**
     * Render a meaningful audit summary card
     */
    renderAuditCard(summary) {
        const badgeClass = {
            'error': 'error',
            'success': 'success',
            'warning': 'warning'
        }[summary.level] || 'info';

        return `
            <div class="audit-entry">
                <div class="entry-icon">${summary.icon}</div>
                <div class="entry-title">${this.formatCategoryName(summary.category)}</div>
                <div class="entry-summary">
                    <strong>${summary.count}</strong> operations | 
                    <strong style="color: #06ffa5;">${summary.successRate}%</strong> successful
                    <div style="margin-top: 0.5rem; font-size: 0.9rem; color: rgba(255,255,255,0.7);">
                        Last: ${summary.lastLog}
                    </div>
                </div>
                <div class="entry-meta">
                    <span>${new Date(summary.timestamp).toLocaleTimeString()}</span>
                    <span class="entry-badge ${badgeClass}">${summary.level}</span>
                </div>
            </div>
        `;
    }

    /**
     * Format category name for display
     */
    formatCategoryName(category) {
        const names = {
            'middleware': 'Middleware',
            'governance': 'Governance',
            'state_management': 'State Management',
            'orchestration': 'Orchestration',
            'validation': 'Validation',
            'infrastructure': 'Infrastructure',
            'audit': 'Audit Trail',
            'unknown': 'Operations'
        };
        return names[category] || category.replace(/_/g, ' ').toUpperCase();
    }

    /**
     * Refresh all data
     */
    async refresh() {
        await this.loadAuditLogs();
        this.updateMetrics();
        this.renderCharts();
        this.renderAuditEntries();
    }
}

// Global instance
let auditAnalytics = null;

/**
 * Toggle between formatted and JSON view
 */
function toggleAuditView() {
    if (auditAnalytics) {
        auditAnalytics.toggleView();
    }
}

/**
 * Initialize when DOM is ready
 */
document.addEventListener('DOMContentLoaded', async () => {
    auditAnalytics = new AuditAnalytics();
    await auditAnalytics.initialize();
});
